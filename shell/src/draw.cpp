const uint8_t *glyph(char ch) {
  if (ch >= 'a' && ch <= 'z') ch = static_cast<char>(ch - 'a' + 'A');
  if (ch >= 'A' && ch <= 'Z') return kFont5x7[ch - 'A'];
  if (ch >= '0' && ch <= '9') return kFont5x7[26 + ch - '0'];
  for (const auto &p : kPunct)
    if (p.ch == ch) return p.rows;
  return nullptr;  // space and unknown characters
}

void blend_px(uint8_t *p, PixelFormat fmt, int bpp, int r, int g, int b, float a) {
  auto mix = [a](int dst, int src) { return static_cast<int>(dst + (src - dst) * a + 0.5f); };
  if (bpp == 4) {  // XRGB8888, little endian: B G R X
    p[0] = static_cast<uint8_t>(mix(p[0], b));
    p[1] = static_cast<uint8_t>(mix(p[1], g));
    p[2] = static_cast<uint8_t>(mix(p[2], r));
    return;
  }
  uint16_t v;
  memcpy(&v, p, 2);
  int R, G, B;
  if (fmt == PixelFormat::RGB565) {
    R = (v >> 11) & 31; G = (v >> 5) & 63; B = v & 31;
    R = R << 3 | R >> 2; G = G << 2 | G >> 4; B = B << 3 | B >> 2;
    R = mix(R, r); G = mix(G, g); B = mix(B, b);
    v = static_cast<uint16_t>((R >> 3) << 11 | (G >> 2) << 5 | (B >> 3));
  } else {  // 0RGB1555
    R = (v >> 10) & 31; G = (v >> 5) & 31; B = v & 31;
    R = R << 3 | R >> 2; G = G << 3 | G >> 2; B = B << 3 | B >> 2;
    R = mix(R, r); G = mix(G, g); B = mix(B, b);
    v = static_cast<uint16_t>((R >> 3) << 10 | (G >> 3) << 5 | (B >> 3));
  }
  memcpy(p, &v, 2);
}

