void plot(Frame &f, int x, int y, uint32_t rgb, float a) {
  if (x < 0 || y < 0 || x >= f.w || y >= f.h) return;
  blend_px(&f.data[(static_cast<size_t>(y) * f.w + x) * f.bpp], f.fmt, f.bpp, (rgb >> 16) & 255, (rgb >> 8) & 255,
           rgb & 255, a);
}

void fill_rect(Frame &f, int x, int y, int w, int h, uint32_t rgb, float a) {
  const int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y;
  const int x1 = x + w > f.w ? f.w : x + w, y1 = y + h > f.h ? f.h : y + h;
  for (int yy = y0; yy < y1; ++yy)
    for (int xx = x0; xx < x1; ++xx) plot(f, xx, yy, rgb, a);
}

std::string glyph_utf8(const std::string &s) {
  std::string out;
  for (char c : s) {
    switch (c) {
      case kArrowUp: out += "\xE2\x86\x91"; break;
      case kArrowDown: out += "\xE2\x86\x93"; break;
      case kArrowRight: out += "\xE2\x86\x92"; break;
      case kArrowLeft: out += "\xE2\x86\x90"; break;
      default: out += c;
    }
  }
  return out;
}

int text_width(const std::string &s, int scale) { return static_cast<int>(s.size()) * 6 * scale; }

void draw_text(Frame &f, int x, int y, const std::string &s, uint32_t rgb, float a, int scale, bool shadow) {
  for (int pass = shadow ? 0 : 1; pass < 2; ++pass) {  // pass 0: 1 px shadow, pass 1: text
    int x0 = x + (pass == 0 ? scale : 0);
    const int y0 = y + (pass == 0 ? scale : 0);
    for (char ch : s) {
      if (const uint8_t *g = glyph(ch))
        for (int row = 0; row < 7; ++row)
          for (int col = 0; col < 5; ++col)
            if (g[row] & (0x10 >> col)) {
              const uint32_t c = pass == 0 ? 0x181008u : rgb;
              const float al = pass == 0 ? a * 0.8f : a;
              if (scale == 1) plot(f, x0 + col, y0 + row, c, al);
              else fill_rect(f, x0 + col * scale, y0 + row * scale, scale, scale, c, al);
            }
      x0 += 6 * scale;
    }
  }
}

